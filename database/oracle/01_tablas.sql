-- =====================================================================
-- 8. INDICES ESPECIALES
--    Un hallazgo y un reporte de perdida solo pueden tener UNA
--    coincidencia CONFIRMADA (las DESCARTADAS no cuentan: el CASE
--    devuelve NULL y Oracle no indexa filas con todo NULL).
-- =====================================================================
CREATE UNIQUE INDEX UX_COINC_CONF_HALL ON COINCIDENCIA (CASE ESTADO WHEN 'CONFIRMADA' THEN ID_HALLAZGO END);
CREATE UNIQUE INDEX UX_COINC_CONF_PERD ON COINCIDENCIA (CASE ESTADO WHEN 'CONFIRMADA' THEN ID_REPORTE_PERDIDA END);


