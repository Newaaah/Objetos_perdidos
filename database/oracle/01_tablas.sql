-- =====================================================================
-- 2. CATALOGOS
-- =====================================================================

-- Areas de trabajo del personal (Seguridad, Mesa de Ayuda, Limpieza...)
CREATE TABLE AREA (
    ID_AREA   NUMBER(19,0)       NOT NULL,
    NOMBRE    VARCHAR2(50 CHAR)  NOT NULL,
    CONSTRAINT PK_AREA        PRIMARY KEY (ID_AREA),
    CONSTRAINT UK_AREA_NOMBRE UNIQUE (NOMBRE)
);

-- Carreras de los estudiantes
CREATE TABLE CARRERA (
    ID_CARRERA  NUMBER(19,0)       NOT NULL,
    NOMBRE      VARCHAR2(50 CHAR)  NOT NULL,
    CONSTRAINT PK_CARRERA        PRIMARY KEY (ID_CARRERA),
    CONSTRAINT UK_CARRERA_NOMBRE UNIQUE (NOMBRE)
);

-- Categorias de objetos (Electronica, Documentos, Llaves...)
CREATE TABLE CATEGORIA (
    ID_CATEGORIA  NUMBER(19,0)       NOT NULL,
    NOMBRE        VARCHAR2(50 CHAR)  NOT NULL,
    CONSTRAINT PK_CATEGORIA        PRIMARY KEY (ID_CATEGORIA),
    CONSTRAINT UK_CATEGORIA_NOMBRE UNIQUE (NOMBRE)
);

-- Lugares del campus. Los puntos de recepcion (Garita, Mesa de Partes,
-- Limpieza) llevan la palabra "recepcion" en DETALLE.
CREATE TABLE UBICACION (
    ID_UBICACION  NUMBER(19,0)        NOT NULL,
    DETALLE       VARCHAR2(255 CHAR),
    NOMBRE        VARCHAR2(100 CHAR)  NOT NULL,
    CONSTRAINT PK_UBICACION        PRIMARY KEY (ID_UBICACION),
    CONSTRAINT UK_UBICACION_NOMBRE UNIQUE (NOMBRE)
);


-- =====================================================================
-- 3. PERSONAS Y ACCESO
-- =====================================================================

-- Datos comunes de toda persona (estudiante, personal o administrador)
CREATE TABLE PERSONA (
    ID_PERSONA           NUMBER(19,0)       NOT NULL,
    APELLIDOS            VARCHAR2(50 CHAR)  NOT NULL,
    DOCUMENTO_IDENTIDAD  VARCHAR2(20 CHAR)  NOT NULL,
    NOMBRES              VARCHAR2(50 CHAR)  NOT NULL,
    TELEFONO             VARCHAR2(50 CHAR),
    TIPO_DOCUMENTO       VARCHAR2(50 CHAR)  NOT NULL,
    CONSTRAINT PK_PERSONA           PRIMARY KEY (ID_PERSONA),
    CONSTRAINT UK_PERSONA_DOCUMENTO UNIQUE (TIPO_DOCUMENTO, DOCUMENTO_IDENTIDAD)
);

-- Estudiante (especializacion de PERSONA, comparte el ID)
CREATE TABLE ESTUDIANTE (
    ID_PERSONA  NUMBER(19,0)       NOT NULL,
    CICLO       NUMBER(2,0),
    CODIGO_UNI  CHAR(9)            NOT NULL,
    ESTADO      VARCHAR2(20 CHAR)  NOT NULL,
    ID_CARRERA  NUMBER(19,0)       NOT NULL,
    CONSTRAINT PK_ESTUDIANTE        PRIMARY KEY (ID_PERSONA),
    CONSTRAINT UK_ESTUDIANTE_CODIGO UNIQUE (CODIGO_UNI),
    CONSTRAINT CK_ESTUDIANTE_ESTADO CHECK (ESTADO IN ('ACTIVO', 'INACTIVO'))
);

-- Personal de la universidad (especializacion de PERSONA)
CREATE TABLE PERSONAL (
    ID_PERSONA  NUMBER(19,0)        NOT NULL,
    CARGO       VARCHAR2(100 CHAR)  NOT NULL,
    ESTADO      VARCHAR2(20 CHAR)   NOT NULL,
    ID_AREA     NUMBER(19,0)        NOT NULL,
    CONSTRAINT PK_PERSONAL        PRIMARY KEY (ID_PERSONA),
    CONSTRAINT CK_PERSONAL_ESTADO CHECK (ESTADO IN ('ACTIVO', 'INACTIVO'))
);

-- En que punto del campus trabaja cada personal y desde cuando
CREATE TABLE PERSONAL_UBICACION (
    ID_ASIGNACION  NUMBER(19,0)  NOT NULL,
    FECHA_FIN      DATE,
    FECHA_INICIO   DATE          NOT NULL,
    ID_PERSONA     NUMBER(19,0)  NOT NULL,
    ID_UBICACION   NUMBER(19,0)  NOT NULL,
    CONSTRAINT PK_PERSONAL_UBICACION PRIMARY KEY (ID_ASIGNACION)
);

-- Cuenta de acceso. PASSWORD guarda el hash BCrypt (puede ser NULL
-- para estudiantes que ingresan solo con codigo o DNI).
CREATE TABLE USUARIO (
    ID_PERSONA  NUMBER(19,0)        NOT NULL,
    ESTADO      VARCHAR2(20 CHAR)   NOT NULL,
    PASSWORD    VARCHAR2(255 CHAR),
    ROL         VARCHAR2(50 CHAR)   NOT NULL,
    CONSTRAINT PK_USUARIO        PRIMARY KEY (ID_PERSONA),
    CONSTRAINT CK_USUARIO_ESTADO CHECK (ESTADO IN ('ACTIVO', 'INACTIVO')),
    CONSTRAINT CK_USUARIO_ROL    CHECK (ROL IN ('ESTUDIANTE', 'PERSONAL', 'ADMIN'))
);


-- =====================================================================
-- 4. OBJETOS Y REPORTES
-- =====================================================================

-- Descripcion de un objeto (perdido o encontrado)
CREATE TABLE OBJETO (
    ID_OBJETO     NUMBER(19,0)        NOT NULL,
    COLOR         VARCHAR2(50 CHAR),
    DESCRIPCION   VARCHAR2(255 CHAR)  NOT NULL,
    MARCA         VARCHAR2(100 CHAR),
    NOMBRE        VARCHAR2(100 CHAR)  NOT NULL,
    ID_CATEGORIA  NUMBER(19,0)        NOT NULL,
    CONSTRAINT PK_OBJETO PRIMARY KEY (ID_OBJETO)
);

-- Un estudiante reporta que perdio algo
CREATE TABLE REPORTE_PERDIDA (
    ID_REPORTE_PERDIDA    NUMBER(19,0)        NOT NULL,
    ESTADO                VARCHAR2(20 CHAR)   NOT NULL,
    FECHA_PERDIDA         DATE,
    FECHA_REPORTE         TIMESTAMP(6)        NOT NULL,
    IMAGEN                VARCHAR2(255 CHAR),
    ID_OBJETO             NUMBER(19,0)        NOT NULL,
    ID_PERSONA            NUMBER(19,0)        NOT NULL,
    ID_UBICACION_PERDIDA  NUMBER(19,0),
    CONSTRAINT PK_REPORTE_PERDIDA        PRIMARY KEY (ID_REPORTE_PERDIDA),
    CONSTRAINT UK_REPORTE_PERDIDA_OBJETO UNIQUE (ID_OBJETO),
    CONSTRAINT CK_REPORTE_PERDIDA_ESTADO CHECK (ESTADO IN ('REPORTADO', 'RECUPERADO', 'CANCELADO'))
);

-- Un estudiante reporta que encontro algo (con foto)
CREATE TABLE REPORTE_HALLAZGOS (
    ID_HALLAZGO              NUMBER(19,0)        NOT NULL,
    ESTADO                   VARCHAR2(20 CHAR)   NOT NULL,
    FECHA_REPORTE            TIMESTAMP(6)        NOT NULL,
    FECHA_REVISION           TIMESTAMP(6),
    IMAGEN_REF               VARCHAR2(255 CHAR)  NOT NULL,
    OBSERVACION              VARCHAR2(255 CHAR),
    ID_OBJETO                NUMBER(19,0)        NOT NULL,
    ID_PERSONA               NUMBER(19,0)        NOT NULL,
    ID_PERSONA_REVISOR       NUMBER(19,0),
    ID_UBICACION_DESTINO     NUMBER(19,0)        NOT NULL,
    ID_UBICACION_ENCONTRADO  NUMBER(19,0)        NOT NULL,
    CONSTRAINT PK_REPORTE_HALLAZGOS        PRIMARY KEY (ID_HALLAZGO),
    CONSTRAINT UK_REPORTE_HALLAZGOS_OBJETO UNIQUE (ID_OBJETO),
    CONSTRAINT CK_REPORTE_HALLAZGOS_ESTADO CHECK (ESTADO IN ('PENDIENTE', 'APROBADO', 'RECHAZADO', 'CANCELADO'))
);


-- =====================================================================
-- 5. CUSTODIA, COINCIDENCIAS Y ENTREGAS
-- =====================================================================

-- Objeto que la UPeU tiene fisicamente (Garita, Mesa de Partes, Limpieza)
CREATE TABLE OBJETOS_CUSTODIADOS (
    ID_CUSTODIA              NUMBER(19,0)        NOT NULL,
    FECHA_REGISTRO           TIMESTAMP(6)        NOT NULL,
    IMAGEN                   VARCHAR2(255 CHAR),
    OBSERVACION_RECEPCION    VARCHAR2(255 CHAR),
    ID_HALLAZGO              NUMBER(19,0),
    ID_OBJETO                NUMBER(19,0)        NOT NULL,
    ID_PERSONA_ENTREGA       NUMBER(19,0),
    ID_PERSONAL_REGISTRA     NUMBER(19,0)        NOT NULL,
    ID_UBICACION_ACTUAL      NUMBER(19,0)        NOT NULL,
    ID_UBICACION_ENCONTRADO  NUMBER(19,0),
    CONSTRAINT PK_OBJETOS_CUSTODIADOS PRIMARY KEY (ID_CUSTODIA),
    CONSTRAINT UK_CUSTODIA_HALLAZGO   UNIQUE (ID_HALLAZGO)
);

-- Decision del personal: este hallazgo corresponde (o no) a esta perdida
CREATE TABLE COINCIDENCIA (
    ID_COINCIDENCIA      NUMBER(19,0)        NOT NULL,
    ESTADO               VARCHAR2(20 CHAR)   NOT NULL,
    FECHA_REVISION       TIMESTAMP(6)        NOT NULL,
    OBSERVACION          VARCHAR2(255 CHAR)  NOT NULL,
    PUNTAJE              NUMBER(3,0)         NOT NULL,
    ID_HALLAZGO          NUMBER(19,0)        NOT NULL,
    ID_PERSONAL_REVISOR  NUMBER(19,0)        NOT NULL,
    ID_REPORTE_PERDIDA   NUMBER(19,0)        NOT NULL,
    CONSTRAINT PK_COINCIDENCIA        PRIMARY KEY (ID_COINCIDENCIA),
    CONSTRAINT UK_COINCIDENCIA_PAR    UNIQUE (ID_HALLAZGO, ID_REPORTE_PERDIDA),
    CONSTRAINT CK_COINCIDENCIA_ESTADO CHECK (ESTADO IN ('CONFIRMADA', 'DESCARTADA'))
);

-- Devolucion del objeto a su dueno (con foto de evidencia)
CREATE TABLE ENTREGA (
    ID_ENTREGA                NUMBER(19,0)        NOT NULL,
    FECHA_ENTREGA             TIMESTAMP(6)        NOT NULL,
    FOTO_EVIDENCIA            VARCHAR2(255 CHAR)  NOT NULL,
    OBSERVACION_VERIFICACION  VARCHAR2(255 CHAR)  NOT NULL,
    ID_COINCIDENCIA           NUMBER(19,0),
    ID_CUSTODIA               NUMBER(19,0)        NOT NULL,
    ID_PERSONA                NUMBER(19,0)        NOT NULL,
    ID_PERSONAL               NUMBER(19,0)        NOT NULL,
    ID_REPORTE_PERDIDA        NUMBER(19,0),
    CONSTRAINT PK_ENTREGA              PRIMARY KEY (ID_ENTREGA),
    CONSTRAINT UK_ENTREGA_COINCIDENCIA UNIQUE (ID_COINCIDENCIA),
    CONSTRAINT UK_ENTREGA_CUSTODIA     UNIQUE (ID_CUSTODIA),
    CONSTRAINT UK_ENTREGA_PERDIDA      UNIQUE (ID_REPORTE_PERDIDA)
);


-- =====================================================================
-- 6. RECLAMOS, INCIDENCIAS Y NOTIFICACIONES
-- =====================================================================

-- RECLAMO: un estudiante objeta una entrega.
-- INCIDENCIA: el personal registra un problema durante la custodia.
CREATE TABLE RECLAMOS (
    ID_RECLAMO            NUMBER(19,0)        NOT NULL,
    DESCRIPCION           VARCHAR2(255 CHAR)  NOT NULL,
    ESTADO                VARCHAR2(20 CHAR)   NOT NULL,
    EVIDENCIA             VARCHAR2(255 CHAR),
    FECHA_REGISTRO        TIMESTAMP(6)        NOT NULL,
    FECHA_RESOLUCION      TIMESTAMP(6),
    RESOLUCION            VARCHAR2(500 CHAR),
    TIPO_RECLAMO          VARCHAR2(20 CHAR)   NOT NULL,
    ID_CUSTODIA           NUMBER(19,0),
    ID_ENTREGA            NUMBER(19,0),
    ID_HALLAZGO           NUMBER(19,0),
    ID_PERSONA_RECLAMA    NUMBER(19,0),
    ID_PERSONAL_REGISTRA  NUMBER(19,0),
    CONSTRAINT PK_RECLAMOS        PRIMARY KEY (ID_RECLAMO),
    CONSTRAINT CK_RECLAMOS_TIPO   CHECK (TIPO_RECLAMO IN ('RECLAMO', 'INCIDENCIA')),
    CONSTRAINT CK_RECLAMOS_ESTADO CHECK (ESTADO IN ('PENDIENTE', 'EN_REVISION', 'APROBADO', 'RECHAZADO', 'RESUELTO')),
    -- Un RECLAMO se cierra como APROBADO/RECHAZADO; una INCIDENCIA como RESUELTO
    CONSTRAINT CK_RECLAMOS_ESTADO_TIPO CHECK (
           (TIPO_RECLAMO = 'RECLAMO'    AND ESTADO IN ('PENDIENTE', 'EN_REVISION', 'APROBADO', 'RECHAZADO'))
        OR (TIPO_RECLAMO = 'INCIDENCIA' AND ESTADO IN ('PENDIENTE', 'EN_REVISION', 'RESUELTO'))
    )
);

-- Bandeja de avisos de cada persona (la campanita)
CREATE TABLE NOTIFICACIONES (
    ID_NOTIFICACION     NUMBER(19,0)        NOT NULL,
    FECHA_CREACION      TIMESTAMP(6)        NOT NULL,
    LEIDA               NUMBER(1,0)         NOT NULL,
    MENSAJE             VARCHAR2(255 CHAR)  NOT NULL,
    TIPO                VARCHAR2(40 CHAR)   NOT NULL,
    TITULO              VARCHAR2(100 CHAR)  NOT NULL,
    ID_CUSTODIA         NUMBER(19,0),
    ID_HALLAZGO         NUMBER(19,0),
    ID_PERSONA          NUMBER(19,0)        NOT NULL,
    ID_REPORTE_PERDIDA  NUMBER(19,0),
    CONSTRAINT PK_NOTIFICACIONES   PRIMARY KEY (ID_NOTIFICACION),
    CONSTRAINT CK_NOTIFICACIONES_TIPO CHECK (TIPO IN (
        'HALLAZGO_APROBADO',
        'HALLAZGO_RECHAZADO',
        'POSIBLE_COINCIDENCIA',
        'OBJETO_EN_CUSTODIA',
        'ENTREGA_REGISTRADA',
        'HALLAZGO_PENDIENTE_RECEPCION',
        'RECLAMO_REGISTRADO',
        'RECLAMO_RESUELTO'
    ))
);


